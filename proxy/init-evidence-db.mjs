import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SCHEMA_VERSION = 6;
// Forward steps for databases created by an older schema, keyed by the
// version they upgrade FROM. Each must reproduce the schema files exactly:
// the structure check below still runs afterwards, so a step that drifts from
// the .sql text is refused rather than silently accepted.
const MIGRATIONS = {
  2: `CREATE TABLE call_assessments (
 key TEXT NOT NULL PRIMARY KEY,
 call_id TEXT,
 model TEXT,
 created_at_ms INTEGER NOT NULL CHECK (typeof(created_at_ms)='integer'),
 body_json TEXT NOT NULL CHECK (json_valid(body_json))
);
CREATE INDEX call_assessments_call ON call_assessments(call_id, created_at_ms);`,
  3: `CREATE TABLE workspace_snapshots (
 id TEXT NOT NULL PRIMARY KEY,
 session_id TEXT NOT NULL,
 agent_session_id TEXT,
 taken_on TEXT NOT NULL CHECK (taken_on IN ('prompt','tool')),
 call_id TEXT,
 commit_sha TEXT NOT NULL,
 parent_sha TEXT,
 changed INTEGER NOT NULL CHECK (changed IN (0,1)),
 taken_at_ms INTEGER NOT NULL CHECK (typeof(taken_at_ms)='integer'),
 changes_json TEXT NOT NULL CHECK (json_valid(changes_json))
);
CREATE INDEX workspace_snapshots_session ON workspace_snapshots(session_id, taken_at_ms);
CREATE INDEX workspace_snapshots_call ON workspace_snapshots(call_id);`,
  // No table changes. Version 5 seeds catalog version 2 (every syscall group,
  // not files only) beside whatever catalog the database already holds: the
  // classification tables are append-only, so the older rows stay.
  4: '',
  // Version 6 adds the derived search index. Read from the schema file
  // itself so the step cannot drift from what a fresh database gets.
  5: readFileSync(new URL('./schema/search.sql', import.meta.url), 'utf8'),
};
/** The version from which a database holds catalog version 2. */
const CATALOG_SINCE = 5;
export const CATALOG_VERSION_ID = 'syscall-catalog-v2';
const modules = ['agent_intent.sql', 'runtime_evidence.sql', 'classification.sql', 'file_context.sql', 'shared_storage.sql', 'auxiliary.sql', 'search.sql'];
const fileLabels = [
  ['source_code', 'Source code', 'Program source files.'],
  ['configuration', 'Configuration', 'Configuration for applications or tools.'],
  ['potentially_sensitive', 'Potentially sensitive', 'May contain secrets or other sensitive information; not proof of contents.'],
  ['documentation', 'Documentation', 'Project documentation and notes.'],
  ['generated_output', 'Generated output', 'Files generated by tools or builds.'],
  ['temporary', 'Temporary', 'Files intended for temporary use.'],
];

function schemaSql() {
  return modules.map(name => {
    let sql = readFileSync(new URL(`./schema/${name}`, import.meta.url), 'utf8');
    // The agent-only script remains directly importable. The combined loader
    // owns the transaction and foreign-key PRAGMA for all modules.
    if (name === 'agent_intent.sql') {
      sql = sql.replace(/^PRAGMA foreign_keys = ON;\r?\n/m, '')
        .replace(/^BEGIN TRANSACTION;\r?\n/m, '').replace(/^COMMIT;\s*$/m, '');
    }
    return sql;
  }).join('\n');
}

function structure(db) {
  return db.prepare("SELECT type,name,tbl_name,sql FROM sqlite_schema WHERE name NOT LIKE 'sqlite_%' ORDER BY type,name").all();
}

function catalogSeed() {
  const source = new DatabaseSync(':memory:');
  try {
    source.exec(readFileSync(new URL('../worker/sandbox/syscall_catalog.sql', import.meta.url), 'utf8'));
    const versions = source.prepare('SELECT DISTINCT catalog_version FROM syscall_catalog').all();
    if (versions.length !== 1 || versions[0].catalog_version !== 2) throw Error('Unsupported source catalog version');
    const levels = source.prepare('SELECT level,label,description FROM syscall_impact_levels ORDER BY level').all();
    const categories = source.prepare('SELECT category_id AS id,label,description FROM syscall_categories ORDER BY category_id').all();
    const rules = source.prepare(`SELECT syscall_name,description,category_id,default_impact_level,
      classification_rule AS rule_identifier,required_evidence,interpretation_notes
      FROM syscall_catalog ORDER BY syscall_name`).all().map(({ required_evidence, ...row }) => ({
        ...row, required_evidence_json: JSON.stringify([required_evidence]),
      }));
    const digest = createHash('sha256').update(JSON.stringify({ catalog_version: '2', levels, categories, rules })).digest('hex');
    return { levels, categories, rules, digest };
  } finally { source.close(); }
}

function same(actual, expected, description) {
  // Compare values independent of object property insertion order.
  const canonical = value => Array.isArray(value) ? value.map(canonical)
    : value && typeof value === 'object' ? Object.fromEntries(Object.keys(value).sort().map(k => [k, canonical(value[k])])) : value;
  if (JSON.stringify(canonical(actual)) !== JSON.stringify(canonical(expected))) {
    throw Error(`Incompatible ${description}; refusing to overwrite existing data`);
  }
}

function insertOrVerify(db, table, key, row, fresh) {
  const existing = db.prepare(`SELECT * FROM ${table} WHERE ${key}=?`).get(row[key]);
  if (existing) same(existing, row, `${table} seed ${row[key]}`);
  else {
    if (!fresh) throw Error(`Missing ${table} seed ${row[key]}`);
    db.prepare(`INSERT INTO ${table} (${Object.keys(row).join(',')}) VALUES (${Object.keys(row).map(() => '?').join(',')})`).run(...Object.values(row));
  }
}

/** `adding` is true for a database that predates this catalog version: its
 * new categories, version and rules are then added, not reported missing. */
function seed(db, data, fresh, adding = false) {
  for (const row of data.levels) insertOrVerify(db, 'classification_impact_levels', 'level', row, fresh);
  for (const row of data.categories) insertOrVerify(db, 'classification_categories', 'id', row, fresh || adding);
  const version = db.prepare('SELECT * FROM classification_versions WHERE id=?').get(CATALOG_VERSION_ID);
  if (version) {
    same({ catalog_version: version.catalog_version, classifier_version: version.classifier_version, content_sha256: version.content_sha256 },
      { catalog_version: '2', classifier_version: 'not-implemented', content_sha256: data.digest }, 'catalog version');
    const rules = db.prepare(`SELECT syscall_name,description,category_id,default_impact_level,rule_identifier,
      required_evidence_json,interpretation_notes FROM classification_syscall_rules WHERE version_id=? ORDER BY syscall_name`).all(CATALOG_VERSION_ID);
    same(rules, data.rules, 'catalog rules');
  } else {
    if (!fresh && !adding) throw Error('Missing catalog version in initialized database');
    db.prepare('INSERT INTO classification_versions VALUES (?,?,?,?,?,?)').run(
      CATALOG_VERSION_ID, '2', 'not-implemented', data.digest, Date.now(),
      'Syscall catalog version 2, every group. No classifier writes results here: the sandbox host draws its facts from the same catalog.');
    for (const row of data.rules) {
      const full = { version_id: CATALOG_VERSION_ID, ...row };
      db.prepare(`INSERT INTO classification_syscall_rules (${Object.keys(full).join(',')}) VALUES (${Object.keys(full).map(() => '?').join(',')})`).run(...Object.values(full));
    }
  }
  for (const [id, label, description] of fileLabels) insertOrVerify(db, 'file_labels', 'id', { id, label, description }, fresh);
}

/** Verifies an existing database is compatible without mutating it. */
export function verifyEvidenceDatabase(outputPath) {
  if (typeof outputPath !== 'string' || !outputPath.trim() || outputPath === ':memory:') {
    throw Error('An explicit standalone database file path is required');
  }
  if (!existsSync(outputPath)) {
    throw Error(`Database file does not exist: ${outputPath}`);
  }
  const path = realpathSync(outputPath);
  const sql = schemaSql();
  const reference = new DatabaseSync(':memory:');
  let db;
  try {
    reference.exec('PRAGMA foreign_keys=ON');
    reference.exec(sql);
    const expected = structure(reference);
    db = new DatabaseSync(path, { readOnly: true });
    const existing = structure(db);
    const version = db.prepare('PRAGMA user_version').get()?.user_version;
    if (version !== SCHEMA_VERSION) {
      throw Error(`Incompatible schema version ${version}; expected ${SCHEMA_VERSION}`);
    }
    same(existing, expected, 'schema structure');
    return { path, schemaVersion: version };
  } finally {
    db?.close();
    reference.close();
  }
}

/** Creates a new standalone database, or verifies an existing compatible one. */
export function initializeEvidenceDatabase(outputPath) {
  if (typeof outputPath !== 'string' || !outputPath.trim() || outputPath === ':memory:') {
    throw Error('An explicit standalone database file path is required');
  }
  const path = existsSync(outputPath) ? realpathSync(outputPath) : resolve(outputPath);
  const livePaths = [resolve('.raytace/raytace.db'), '/var/lib/raytace/runtime.db'];
  if (livePaths.includes(path)) throw Error('Refusing a live database path');
  const sql = schemaSql();
  const data = catalogSeed();
  const reference = new DatabaseSync(':memory:');
  let db;
  try {
    reference.exec('PRAGMA foreign_keys=ON');
    reference.exec(sql);
    const expected = structure(reference);
    db = new DatabaseSync(path);
    db.exec('PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000; BEGIN IMMEDIATE');
    try {
      const existing = structure(db);
      const version = db.prepare('PRAGMA user_version').get().user_version;
      const fresh = existing.length === 0 && version === 0;
      // The RayTrace CLI's own first schema (version 1) was the agent-intent,
      // shared-storage and auxiliary modules alone, before the CLI took the
      // sandbox schema on. Everything it lacks is added; everything it has must
      // match exactly, which the structure check below still makes sure of.
      const cliFirst = !fresh && version === 1 && !existing.some((object) => object.name === 'runtime_sandboxes');
      if (fresh) db.exec(sql);
      else if (cliFirst) {
        const have = new Set(existing.map((object) => `${object.type}:${object.name}`));
        const missing = expected.filter((object) => object.sql && !have.has(`${object.type}:${object.name}`));
        for (const type of ['table', 'index', 'trigger', 'view']) {
          // A full-text table makes its own shadow tables: one made that way is skipped.
          const exists = db.prepare('SELECT 1 FROM sqlite_schema WHERE type = ? AND name = ?');
          for (const object of missing.filter((item) => item.type === type)) if (!exists.get(object.type, object.name)) db.exec(object.sql);
        }
        same(structure(db), expected, 'schema structure');
      } else {
        if (!(version in MIGRATIONS) && version !== SCHEMA_VERSION) throw Error(`Incompatible schema version ${version}`);
        for (let step = version; step < SCHEMA_VERSION; step += 1) if (MIGRATIONS[step]) db.exec(MIGRATIONS[step]);
        same(structure(db), expected, 'schema structure');
      }
      seed(db, data, fresh || cliFirst, !fresh && version < CATALOG_SINCE);
      if (db.prepare('PRAGMA foreign_key_check').all().length) throw Error('Foreign key integrity check failed');
      db.exec(`PRAGMA user_version=${SCHEMA_VERSION}; COMMIT`);
      return { path, schemaVersion: SCHEMA_VERSION, tables: expected.filter(o => o.type === 'table').length,
        catalogVersion: CATALOG_VERSION_ID, catalogRules: data.rules.length, created: fresh };
    } catch (error) {
      db.exec('ROLLBACK');
      throw error;
    }
  } finally { db?.close(); reference.close(); }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 3) {
    console.error('Usage: node proxy/init-evidence-db.mjs <standalone-database-path>');
    process.exitCode = 1;
  } else {
    try { console.log(JSON.stringify(initializeEvidenceDatabase(process.argv[2]), null, 2)); }
    catch (error) { console.error(error.message); process.exitCode = 1; }
  }
}
